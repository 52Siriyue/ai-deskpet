"""表情占位符 → 真实 emoji 映射（LongCat 回复用 [捂脸] 等腾讯系文本表情）"""
import re

EMOJI_MAP = {
    "捂脸": "🤦", "嘿嘿": "😁", "大笑": "😂", "笑哭": "😂", "哈哈": "😄",
    "哭泣": "😭", "大哭": "😭", "流泪": "😭", "委屈": "😢", "难过": "😔",
    "微笑": "😊", "开心": "😄", "高兴": "😄", "可爱": "🥰", "害羞": "😳",
    "调皮": "😜", "吐舌": "😛", "惊讶": "😲", "惊恐": "😱", "哇": "😮",
    "思考": "🤔", "疑问": "🤔", "无语": "😑", "汗": "😅", "流汗": "😅",
    "生气": "😠", "愤怒": "😡", "白眼": "🙄", "翻白眼": "🙄",
    "爱心": "❤️", "亲亲": "😘", "飞吻": "😘", "色": "😍", "喜欢": "😍",
    "鼓掌": "👏", "赞": "👍", "棒": "👍", "加油": "💪", "耶": "✌️",
    "酷": "😎", "睡觉": "😴", "嘘": "🤫", "拜托": "🥺", "求求": "🥺",
    "坏笑": "😏", "神秘": "🤫", "星星眼": "🤩", "天啊": "😱",
}
EMOJI_TAG_RE = re.compile(r"\[([^\[\]]{1,8})\]")


def fix_emoji(text):
    """把 [表情] 占位符转成真实 emoji；未知标签直接删除"""
    if not text or "[" not in text:
        return text
    return EMOJI_TAG_RE.sub(lambda m: EMOJI_MAP.get(m.group(1), ""), text)
